// The one place VELSCOUR DEFENSE reads the main game's code: it snapshots the data it needs from src/data/ into
// defense/data/art_index.json, so the Defense page never imports a main-game module (and can't disturb it).
// Re-run after the main game adds classes, finishes, held sets, monsters or jingles:
//   node defense/tools/art_index.mjs
import { writeFileSync, readFileSync, mkdirSync } from 'fs';
import { CLASSES } from '../../src/data/classes.js';
import { PALETTES } from '../../src/data/gear.js';
import { CLASS_FOCUS, heldSetOf } from '../../src/data/held.js';
import { BESTIARY } from '../../src/data/bestiary.js';
import { melodies, degMidi, BAR } from '../../src/data/melodies.js';

const root = new URL('../../', import.meta.url);
const enemies = JSON.parse(readFileSync(new URL('assets/sprites/enemies/enemies.json', root), 'utf8'));
const heldIndex = JSON.parse(readFileSync(new URL('assets/sprites/held/index.json', root), 'utf8'));

const classes = {}, held = {};
for (const [id, c] of Object.entries(CLASSES)) {
  const weapon = heldSetOf(c.weapon, 'weapon', id), offhand = heldSetOf(CLASS_FOCUS[id] || 'axe', 'offhand', id);
  classes[id] = { name: c.name, color: c.color, element: c.element, weapon: heldIndex.sets[weapon] ? weapon : null, offhand: heldIndex.sets[offhand] ? offhand : null };
  // every design's name, rarity and element, so cards can be named before a set's atlas loads
  for (const set of [weapon, offhand]) {
    if (!heldIndex.sets[set] || held[set]) continue;
    const s = JSON.parse(readFileSync(new URL(`assets/sprites/held/${set}.json`, root), 'utf8'));
    held[set] = { hand: s.hand, slot: s.slot, designs: s.designs.map((d) => [d.name, d.rarity, d.element]) };
  }
}
const gearN = {};
for (const id of Object.keys(CLASSES)) {
  const g = JSON.parse(readFileSync(new URL(`assets/sprites/gear/${id}/gear.json`, root), 'utf8'));
  gearN[id] = { armor: g.armor.n, bands: g.armor.bands };
}
const helmIndex = JSON.parse(readFileSync(new URL('assets/sprites/gear/helmets/index.json', root), 'utf8'));

const SHEETS = /^(set1|set2|set3|depths_edge)\//;
const monsters = BESTIARY.filter((a) => enemies[a.sheet] && SHEETS.test(a.sheet) && !a.airPirate)
  .map((a) => {
    const o = { id: a.id, sheet: a.sheet, i: a.i, arch: a.arch, name: a.name, h: a.h };
    for (const k of ['el', 'boss', 'lone', 'fly', 'undead', 'demon', 'gore']) if (a[k] !== undefined && a[k] !== false) o[k] = a[k];
    return o;
  });

// the Bard's melodies (one in five of the main game's 2,000): both bars of the right hand, and a bass note per chord
const jingles = melodies().filter((_, i) => i % 5 === 0).map((m) => ({
  name: m.name, tempo: m.tempo,
  mel: [...m.A.rh.map((n) => [n, 0]), ...m.B.rh.map((n) => [n, BAR])].filter(([n]) => !n.r).map(([n, o]) => [n.t + o, n.dur, degMidi(m.key, n.d, n.alt || 0)]),
  bass: [...m.A.chords, ...m.B.chords].map((ch) => degMidi(m.key, ch.bass, 0) - 12),
}));

const out = {
  note: 'Generated by defense/tools/art_index.mjs from the main game\'s src/data. Do not edit.',
  classes, held, gear: gearN, helms: helmIndex.designs.map((d) => [d.id, d.rarity, d.set]),
  palettes: PALETTES.map((p) => ({ name: p.name, tier: p.tier, k: p.k, ramps: p.ramps, glow: p.glow })),
  monsters, jingles,
};
mkdirSync(new URL('../data/', import.meta.url), { recursive: true });
writeFileSync(new URL('../data/art_index.json', import.meta.url), JSON.stringify(out));
console.log(`${Object.keys(classes).length} classes, ${out.palettes.length} finishes, ${monsters.length} monsters (${monsters.filter((m) => m.boss).length} bosses), ${jingles.length} jingles`);
