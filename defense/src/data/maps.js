/**
 * Which battlefield stage n is fought on, and how it is turned: Act I uses the first 30 (as drawn, then transposed,
 * then transposed and flipped); Acts II and III cycle all 40 in the orientations Act I never used ('V' flips top to
 * bottom), so no two stages share a field and a turn.
 */
export function stageMapRef(n) {
  if (n <= 30) return { map: n - 1, tf: '' };
  if (n <= 80) return { map: (n - 31) % 30, tf: n <= 60 ? 'T' : 'TF' };
  if (n <= 200) { const k = n - 81; return { map: k % 40, tf: ['V', 'FV', 'TV'][Math.floor(k / 40)] }; }
  // Acts IV and V: the orientations no act has used yet
  const k = n - 201;
  if (k < 80) return { map: k % 40, tf: k < 40 ? 'F' : 'TFV' };
  return { map: 30 + (k - 80) % 10, tf: k - 80 < 10 ? '' : 'T' };
}
