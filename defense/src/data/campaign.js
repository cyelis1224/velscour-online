export const LEVELS = STAGES.map(([name, blurb], i) => {
  const region = REGIONS[Math.floor(i / 10)], k = i % 10;
  return { n: i + 1, name, blurb, region: region.id, act: region.act, boss: k === 9, lieutenant: k === 4, warlord: k === 7 && region.act > 1 };
});

// 5,000 waves, each harder than the last: Act I's 80 stages share waves 1-1,000 (about 6 to 19 a stage), Acts II and III
// the next 2,000 (about 14 to 19 a stage), Acts IV and V the last 2,000 (18 to 22)
export const TOTAL_WAVES = 5000;
{
  const split = (from, to, lo, hi, total, w0) => {
    const ls = LEVELS.slice(from - 1, to), raw = ls.map((L, i) => lo + (hi - lo) * i / Math.max(1, ls.length - 1));
    const sum = raw.reduce((a, b) => a + b, 0), counts = raw.map((r) => Math.floor(r * total / sum));
    let left = total - counts.reduce((a, b) => a + b, 0);
    for (let i = ls.length - 1; left > 0; i = (i + ls.length - 1) % ls.length) { counts[i]++; left--; }
    let w = w0;
    ls.forEach((L, i) => { L.waves = counts[i]; L.wave0 = w; w += counts[i]; });
  };
  split(1, 80, 6, 19, 1000, 0);
  split(81, 200, 14, 19.4, 2000, 1000);
  split(201, 300, 18, 22, 2000, 3000);
}
export const ACTS = [{ n: 1, name: 'Act I: The Riftgate', from: 1, to: 80 }, { n: 2, name: 'Act II: The Six Scars', from: 81, to: 140 }, { n: 3, name: 'Act III: The Breach', from: 141, to: 200 },
  { n: 4, name: 'Act IV: The Descent', from: 201, to: 250 }, { n: 5, name: 'Act V: The Demon Lord', from: 251, to: 300 }];
export const actOf = (n) => ACTS.find((a) => n >= a.from && n <= a.to) || ACTS[ACTS.length - 1];
