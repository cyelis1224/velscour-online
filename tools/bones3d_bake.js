// Bake the bone gibs (tools/bones3d.html, models in tools/bones3d.js) into the data sheet the game paints:
// assets/sprites/bones.webp + .json (every bone's 16 tumbling turns and its rest poses; src/gfx/bonegibs.js).
// Needs the repo served (python -m http.server 8123), jsDelivr (three.js, for this tool only) and python with Pillow
// for the lossless WebP (the fields must keep their exact values).
//   node tools/bones3d_bake.js [S]     # S: sheet px per world px (default 2)
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { chromium } = require('playwright');

const BASE = process.env.BASE_URL || 'http://localhost:8123';
const ROOT = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ args: (process.env.CHROMIUM_ARGS || '').split(' ').filter(Boolean) });
  const page = await browser.newPage();
  page.on('console', (m) => ['error', 'warning'].includes(m.type()) && console.log('[page]', m.text()));
  page.on('pageerror', (e) => console.log('[page]', e.message));
  await page.goto(`${BASE}/tools/bones3d.html?bake`);
  await page.waitForFunction(() => window.BONES3D, null, { timeout: 60000 });
  const r = await page.evaluate((S) => window.BONES3D.bake(S), Number(process.argv[2] || 2));
  await browser.close();
  const dir = path.join(ROOT, 'assets/sprites'), png = path.join(dir, 'bones.png');
  fs.writeFileSync(png, Buffer.from(r.png.split(',')[1], 'base64'));
  fs.writeFileSync(path.join(dir, 'bones.json'), JSON.stringify({ _: 'generated by tools/bones3d_bake.js; do not edit', ...r.meta }));
  const py = 'import sys, os\nfrom PIL import Image\np = sys.argv[1]\nImage.open(p).save(p[:-4] + ".webp", "WEBP", lossless=True, quality=100, method=6)\nos.remove(p)\n';
  const c = spawnSync(process.env.PYTHON || 'python', ['-c', py, png], { stdio: 'inherit' });
  if (c.status !== 0) { console.log('WebP conversion failed: the PNG is left at', png); process.exitCode = 1; return; }
  const kb = (fs.statSync(path.join(dir, 'bones.webp')).size / 1024).toFixed(0);
  console.log(`bones: ${Object.entries(r.meta.bones).map(([k, b]) => `${k} ${b.t.length}+${b.r.length}`).join(', ')}; S ${r.meta.S}, ${kb} KB, ${r.ms} ms`);
})();
